# Soal: Berdasarkan Example 2.10 dan 2.11, buat program yang membaca
# nama, umur, dan nilai (marks) dari keyboard.
# - umur dibaca sebagai integer
# - marks dibaca sebagai float
# lalu tampilkan semuanya di layar.

print('Input your name: ')
name = input()

print('Input your age: ')
age = int(input())

print('Input your marks: ')
marks = float(input())

print("Name  : " + name)
print("Age   : " + str(age))
print("Marks : " + str(marks))
